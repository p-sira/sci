"""Snapshot SciPy's CODATA 2022 values, SI units, uncertainties, and aliases.

Run with the pinned .venv or uv run. This copies factual data, not SciPy code.
Reference cases live separately in constants_cases.json.
"""
import csv
import json
import subprocess
from pathlib import Path
import numpy as np
import scipy
from scipy import constants as c

assert (np.__version__, scipy.__version__) == ("2.5.4", "1.18.1")
root = Path(__file__).resolve().parents[2]
def quote(s):
    return json.dumps(s, ensure_ascii=False)
with (root / "src/constants/data.rs").open("w") as f:
    f.write('// Generated by tests/scipy/generate_constants.py; SciPy 1.18.1, CODATA 2022.\n')
    f.write('use super::PhysicalConstant;\n\n')
    f.write('/// CODATA 2022 table in SI units, sorted by name. Includes SciPy historical keys.\n')
    f.write('pub static PHYSICAL_CONSTANTS: &[PhysicalConstant] = &[\n')
    for name, (value, unit, uncertainty) in sorted(c.physical_constants.items()):
        f.write(f'    PhysicalConstant {{ name: {quote(name)}, value: {value!r}, unit: {quote(unit)}, uncertainty: {uncertainty!r} }},\n')
    f.write('];\n\n')
    f.write('pub(super) static CURRENT_NAMES: &[&str] = &[\n')
    for name in c.find():
        f.write(f'    {quote(name)},\n')
    f.write('];\n\n')
    for name in sorted(c.__all__):
        value = getattr(c, name)
        if isinstance(value, (int, float)):
            f.write(f'/// SciPy `{name}` constant or conversion factor; SI conventions in the [SciPy constants reference](https://docs.scipy.org/doc/scipy/reference/constants.html).\n')
            literal = "std::f64::consts::PI" if name == "pi" else repr(float(value))
            f.write(f'pub const {"r#dyn" if name == "dyn" else name}: f64 = {literal};\n')
cases = json.loads((root / "tests/scipy/constants_cases.json").read_text())
with (root / "tests/fixtures/constants_expected.csv").open("w", newline="") as f:
    writer = csv.writer(f, lineterminator="\n")
    writer.writerow(["api", "result"])
    for case in cases:
        api = case["api"]
        if api == "find":
            result = ";".join(c.find(case["key"]))
        elif api in {"value", "unit", "precision"}:
            result = getattr(c, api)(case["key"])
        elif api == "convert_temperature":
            result = c.convert_temperature(case["x"], case["from"], case["to"])
        else:
            result = getattr(c, api)(case["x"])
        writer.writerow([api, result])
with (root / "tests/fixtures/constants_table.csv").open("w", newline="") as f:
    writer = csv.writer(f, lineterminator="\n")
    writer.writerow(["name", "value", "unit", "uncertainty"])
    for name, values in sorted(c.physical_constants.items()):
        writer.writerow([name, *values])
with (root / "tests/fixtures/constants_inputs.csv").open("w", newline="") as f:
    writer = csv.writer(f, lineterminator="\n")
    writer.writerow(["api", "argument", "from", "to"])
    for case in cases:
        writer.writerow([case["api"], case.get("key",case.get("x","")),case.get("from",""),case.get("to","")])

subprocess.run(["rustfmt", "--edition", "2024", str(root / "src/constants/data.rs")], check=True)
