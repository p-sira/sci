"""Pinned periodic operator references from input-only JSON.

Run: uv run tests/scipy/generate_fft_periodic.py
Comparisons use 3e-12 absolute plus relative tolerance for short FFT kernels and
hyperbolic multipliers. No expected values are generated by native backends.
"""
import csv
from pathlib import Path
from case_catalog import read_cases
import numpy as np
import scipy
from scipy import fftpack as f
assert (np.__version__,scipy.__version__)==('2.5.4','1.18.1')
ROOT=Path(__file__).resolve().parents[1]
def encode(a):return ';'.join(str(v) for v in np.asarray(a).ravel())
with (ROOT/'fixtures/fft_periodic_inputs.csv').open('w',newline='') as fi,(ROOT/'fixtures/fft_periodic_expected.csv').open('w',newline='') as fe:
    iw=csv.writer(fi,lineterminator='\n');ew=csv.writer(fe,lineterminator='\n')
    iw.writerow(['id','api','re','a','b','h','period','order']);ew.writerow(['id','shape','re','im'])
    for c in read_cases(Path(__file__).with_name('fft_periodic_cases.jsonl')):
        api=c['api'];re=np.array(c.get('re',[]),dtype=float)
        iw.writerow([c['id'],api,encode(re),c.get('a',''),c.get('b',''),c.get('h',''),c.get('period',''),c.get('order','')])
        if api in ('hilbert','ihilbert'):v=getattr(f,api)(re)
        elif api=='diff':v=f.diff(re,c['order'],period=c['period'])
        elif api in ('cc_diff','cs_diff','sc_diff','ss_diff'):v=getattr(f,api)(re,c['a'],c['b'],period=c['period'])
        elif api in ('tilbert','itilbert'):v=getattr(f,api)(re,c['h'],period=c['period'])
        elif api=='shift':v=f.shift(re,c['a'],period=c['period'])
        else:raise ValueError(f'unsupported periodic operator: {api}')
        a=np.atleast_1d(np.asarray(v));ew.writerow([c['id'],encode(a.shape),encode(a.real),encode(a.imag)])
