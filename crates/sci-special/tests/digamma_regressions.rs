#[test]
fn digamma_reflection_poles_and_positive_boundaries() {
    // Independently calculated with scipy.special.digamma (1.17.0).
    for &(x, expected) in &[
        (1e-8_f64, -100000000.57721564),
        (0.5, -1.9635100260214235),
        (1.0, -0.5772156649015329),
        (1.4616321449683622, -9.241265521729427e-17),
        (2.0, 0.42278433509846713),
        (8.0, 2.0156414779556098),
        (9.0, 2.1406414779556098),
        (10.0, 2.251752589066721),
        (100.0, 4.600161852738088),
        (1e20, 46.051701859880914),
        (-0.5, 0.03648997397857651),
        (-2.3, 3.3173231575618236),
    ] {
        let actual = sci_special::gamma::digamma(x);
        assert!(
            (actual - expected).abs() <= 3e-14 * expected.abs().max(1.0),
            "sci_special::gamma::digamma({x}) = {actual}, SciPy = {expected}"
        );
    }
    assert_eq!(sci_special::gamma::digamma(0.0), f64::NEG_INFINITY);
    assert_eq!(sci_special::gamma::digamma(-0.0), f64::INFINITY);
    for x in [-1.0_f64, -2.0, -100.0] {
        assert!(sci_special::gamma::digamma(x).is_nan());
    }
    assert!(sci_special::gamma::digamma(f64::NEG_INFINITY).is_nan());
    assert_eq!(sci_special::gamma::digamma(f64::INFINITY), f64::INFINITY);
    assert!(sci_special::gamma::digamma(f64::NAN).is_nan());
}
